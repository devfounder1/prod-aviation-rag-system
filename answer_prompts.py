def document_question(question: str) -> bool:
    """Strong domain anchors or an explicit question about documentation."""
    return bool(technical_terms(question) or re.search(
        r'документац|по\s+документ|в\s+документ|инструкци|руководств|'
        r'\b(?:documentation|manual)\b', question, re.I))


def wants_brief_answer(question: str) -> bool:
    for match in re.finditer(r'\b(?:кратко|вкратце|коротко|briefly|brief|short|succinct)\b|'
                             r'в\s+двух\s+словах|одним\s+предложением|в\s+[12]\s+предложени', question, re.I):
        prefix = question[max(0,match.start()-25):match.start()]
        if not re.search(r'\b(?:не(?:\s+слишком)?|not)\s*$', prefix, re.I):
            return True
    return False


def document_answer_instruction(question: str) -> str:
    if wants_brief_answer(question):
        return 'В текущем запросе пользователь просит кратко. Дай краткий ответ по источникам с важными условиями и ссылками.'
    return ('В текущем запросе нужен развёрнутый ответ по документации. Раскрой прямой ответ, '
            'назначение, принцип/порядок работы, условия и параметры, ограничения — насколько '
            'это подтверждено источниками. Используй несколько смысловых абзацев/разделов, '
            'а не одну короткую справку. Не наследуй краткость прошлых ответов. '
            'Если данных мало, назови пробелы; не добавляй выдуманных деталей ради объёма.')


def needs_detail_retry(question: str, answer: str, context: str) -> bool:
    """One repair only for broad explanations with substantial source material."""
    broad = re.search(r'что\s+(?:такое|представляет)|как\s+(?:работает|включ|выполн|провер|устро)|'
                      r'расскажи|объясни|поясни|опиши|подробн|разв[её]рнут|'
                      r'\b(?:explain|describe|what\s+is|how\s+does)\b', question, re.I)
    return (not wants_brief_answer(question) and bool(broad)
            and len(context.split()) >= 300 and len(answer.split()) < 180)


