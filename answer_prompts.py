def needs_grounding_review(answer: str, context: str) -> bool:
    return len(context.split()) >= 120 and len(answer.split()) >= 25


def grounding_review_messages(question: str, answer: str, context: str) -> list[BaseMessage]:
    # Keep this pass compact: replaying the full agent prompt/tool schemas and
    # history would crowd the evidence out of a small local context window.
    return [SystemMessage(content=IDENTITY_PROMPT+'\n\nТы — редактор ответа по предоставленным локальным источникам. '+GROUNDING_REVIEW_INSTRUCTION),
            HumanMessage(content='UNTRUSTED SOURCE DATA:\n'+context),
            HumanMessage(content='Исходный вопрос:\n'+question+'\n\nЧерновик для проверки (не источник фактов):\n'+answer),
            SystemMessage(content=document_answer_instruction(question)+'\nНачни с того, что описано в найденных фрагментах. '
                          'Не переноси утверждения из черновика без подтверждения источником. '
                          'Если частота, место генерации, точность синхронизации или иная характеристика '
                          'не указаны, назови их неуказанными. Условие корректности служебного поля '
                          'не является значением времени/счётчика, по которому определяют чётность.')]


def strip_unverified_expansions(answer: str, context: str) -> str:
    """Do not present invented parenthesized acronym expansions as source facts."""
    import re
    normalized_context = ' '.join(context.casefold().split())
    def replace(match: re.Match[str]) -> str:
        expansion = match.group('expansion')
        if re.match(r'\s*[+-]?\d', expansion):
            return match.group(0)
        if not re.search(r'[а-яa-z]', expansion, re.IGNORECASE):
            return match.group(0)
        if ' '.join(expansion.casefold().split()) in normalized_context:
            return match.group(0)
        return match.group('abbr')
    return re.sub(r'\b(?P<abbr>[А-ЯЁA-Z][А-ЯЁA-Z0-9-]{1,20})\s*\((?P<expansion>[^()\n]{3,100})\)',
                  replace, answer)
